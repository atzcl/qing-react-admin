import { readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  readAdminRouteContracts,
  readFeaturePaths,
  readShowcasePaths,
} from './admin-route-contract.mjs'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const routesRoot = resolve(repositoryRoot, 'apps/web-admin/src/routes')
const checkOnly = process.argv.includes('--check')

const auxiliaryPages = [
  '/fallback/403',
  '/fallback/500',
  '/fallback/coming-soon',
  '/fallback/offline',
]

const featurePaths = await readFeaturePaths(resolve(repositoryRoot, 'apps/web-admin/src/features'))
const showcaseEntries = await readShowcasePaths(
  resolve(repositoryRoot, 'apps/web-admin/src/core/showcase-catalog.tsx'),
)
const managedDefinitionPaths = [
  ...new Set([
    ...featurePaths.map((feature) => feature.path),
    ...showcaseEntries.map((entry) => entry.path),
    ...auxiliaryPages,
  ]),
]

function routeSegment(segment) {
  return segment.startsWith(':') ? `$${segment.slice(1)}` : segment
}

function routeFile(definitionPath) {
  const segments = definitionPath.slice(1).split('/').map(routeSegment)
  return resolve(routesRoot, `_app.${segments.join('.')}.tsx`)
}

function routeId(definitionPath) {
  return `/_app/${definitionPath.slice(1).split('/').map(routeSegment).join('/')}`
}

function quoted(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

function routeSource(definitionPath) {
  const analytics = definitionPath === '/dashboard/analytics'
  const beforeLoadCall = `beforeLoadAdminPage(${quoted(definitionPath)}, context.user),`
  const beforeLoad = `  beforeLoad: ({ context }) => ${beforeLoadCall}`
  const imports = [
    "import { createFileRoute } from '@tanstack/react-router'",
    '',
    "import { beforeLoadAdminPage } from '~/core/admin-route'",
    ...(analytics
      ? ["import { analyticsQueryOptions } from '~/features/dashboard/analytics/queries'"]
      : []),
  ]
  const options = [
    beforeLoad.length <= 100 ? beforeLoad : `  beforeLoad: ({ context }) =>\n    ${beforeLoadCall}`,
    ...(analytics
      ? ['  loader: ({ context }) => context.queryClient.ensureQueryData(analyticsQueryOptions),']
      : []),
    `  staticData: { adminPagePath: ${quoted(definitionPath)} },`,
  ]
  return `${imports.join('\n')}\n\n// Generated by scripts/generate-admin-routes.mjs.\nexport const Route = createFileRoute(${quoted(routeId(definitionPath))})({\n${options.join('\n')}\n})\n`
}

const changedManagedFiles = (
  await Promise.all(
    managedDefinitionPaths.map(async (definitionPath) => {
      const file = routeFile(definitionPath)
      const expected = routeSource(definitionPath)
      const current = await readFile(file, 'utf8').catch(() => null)
      if (current === expected) return undefined
      if (!checkOnly) await writeFile(file, expected)
      return checkOnly ? file : undefined
    }),
  )
).filter((file) => file !== undefined)

const managedFiles = new Set(managedDefinitionPaths.map(routeFile))
const existingContracts = await readAdminRouteContracts(routesRoot)
const staleGeneratedFiles = existingContracts
  .filter(
    (contract) =>
      contract.source.includes('// Generated by scripts/generate-admin-routes.mjs.') &&
      !managedFiles.has(contract.file),
  )
  .map((contract) => contract.file)

if (!checkOnly && staleGeneratedFiles.length > 0) {
  await Promise.all(staleGeneratedFiles.map((file) => rm(file)))
}

if (checkOnly && (changedManagedFiles.length > 0 || staleGeneratedFiles.length > 0)) {
  const drift = [...changedManagedFiles, ...staleGeneratedFiles]
  throw new Error(
    `Generated admin routes are stale:\n${drift.map((file) => `  - ${file}`).join('\n')}\nRun pnpm routes:generate.`,
  )
}

const contracts = checkOnly ? existingContracts : await readAdminRouteContracts(routesRoot)
const expectedPaths = new Set([...managedDefinitionPaths])
const contractsByPath = new Map()
const contractErrors = []

for (const contract of contracts) {
  if (contractsByPath.has(contract.adminPagePath)) {
    contractErrors.push(`duplicate route contract for ${contract.adminPagePath}: ${contract.file}`)
  }
  contractsByPath.set(contract.adminPagePath, contract)
  if (!expectedPaths.has(contract.adminPagePath)) {
    contractErrors.push(`route has no page manifest or feature: ${contract.file}`)
  }
}

for (const definitionPath of expectedPaths) {
  const contract = contractsByPath.get(definitionPath)
  if (!contract) {
    contractErrors.push(`page has no explicit route: ${definitionPath}`)
    continue
  }
  const expectedFile = routeFile(definitionPath)
  if (contract.file !== expectedFile) {
    contractErrors.push(`route filename mismatch for ${definitionPath}: ${contract.file}`)
  }
  if (contract.guardPath !== definitionPath) {
    contractErrors.push(`route guard mismatch for ${definitionPath}: ${contract.file}`)
  }
  if (contract.routeId !== routeId(definitionPath)) {
    contractErrors.push(`route ID mismatch for ${definitionPath}: ${contract.file}`)
  }
}

if (contractErrors.length > 0) {
  throw new Error(
    `Admin route contract is inconsistent:\n${contractErrors.map((error) => `  - ${error}`).join('\n')}`,
  )
}

process.stdout.write(
  `${checkOnly ? 'Verified' : 'Generated'} ${contracts.length} TanStack admin route contracts.\n`,
)
