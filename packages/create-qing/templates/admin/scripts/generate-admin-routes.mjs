import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { pageManifest } from '../apps/web-admin/src/core/page-manifest.ts'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const routesRoot = resolve(repositoryRoot, 'apps/web-admin/src/routes')
const checkOnly = process.argv.includes('--check')

const auxiliaryPages = [
  '/fallback/403',
  '/fallback/500',
  '/fallback/coming-soon',
  '/fallback/offline',
]

const definitionPaths = [
  ...new Set([...pageManifest.map((entry) => entry.path), ...auxiliaryPages]),
]

function routeSegment(segment) {
  return segment.startsWith(':') ? `$${segment.slice(1)}` : segment
}

function routeFile(definitionPath) {
  const segments = definitionPath.slice(1).split('/').map(routeSegment)
  return resolve(routesRoot, `_app.${segments.join('.')}.tsx`)
}

function routeId(definitionPath) {
  return `/_app/${definitionPath.slice(1).split('/').map(routeSegment).join('/')}`
}

function quoted(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

function routeSource(definitionPath) {
  const analytics = definitionPath === '/dashboard/analytics'
  const beforeLoadCall = `beforeLoadAdminPage(${quoted(definitionPath)}, context.user),`
  const beforeLoad = `  beforeLoad: ({ context }) => ${beforeLoadCall}`
  const imports = [
    "import { createFileRoute } from '@tanstack/react-router'",
    '',
    "import { beforeLoadAdminPage } from '~/core/admin-route'",
    ...(analytics
      ? ["import { analyticsQueryOptions } from '~/features/dashboard/analytics/queries'"]
      : []),
  ]
  const options = [
    beforeLoad.length <= 100 ? beforeLoad : `  beforeLoad: ({ context }) =>\n    ${beforeLoadCall}`,
    ...(analytics
      ? ['  loader: ({ context }) => context.queryClient.ensureQueryData(analyticsQueryOptions),']
      : []),
    `  staticData: { adminPagePath: ${quoted(definitionPath)} },`,
  ]
  return `${imports.join('\n')}\n\n// Generated by scripts/generate-admin-routes.mjs.\nexport const Route = createFileRoute(${quoted(routeId(definitionPath))})({\n${options.join('\n')}\n})\n`
}

const drift = (
  await Promise.all(
    definitionPaths.map(async (definitionPath) => {
      const file = routeFile(definitionPath)
      const expected = routeSource(definitionPath)
      const current = await readFile(file, 'utf8').catch(() => null)
      if (current === expected) return undefined
      if (!checkOnly) await writeFile(file, expected)
      return checkOnly ? file : undefined
    }),
  )
).filter((file) => file !== undefined)

if (drift.length > 0) {
  throw new Error(
    `Generated admin routes are stale:\n${drift.map((file) => `  - ${file}`).join('\n')}\nRun pnpm routes:generate.`,
  )
}

process.stdout.write(
  `${checkOnly ? 'Verified' : 'Generated'} ${definitionPaths.length} TanStack admin routes.\n`,
)
